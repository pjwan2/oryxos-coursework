<script setup>
import { ref } from 'vue'
import { useRouter } from 'vue-router'
import { api } from '../api.js'
import AsyncState from '../components/AsyncState.vue'
import StatusBadge from '../components/StatusBadge.vue'
import { useResource } from '../composables/useResource.js'

const router = useRouter()
const listing = useResource(() => api('/agents'), { isEmpty: (l) => l.agents.length === 0 })

const form = ref({ name: '', description: '' })
const creating = ref(false)
const createError = ref(null)

async function create() {
  creating.value = true
  createError.value = null
  try {
    const agent = await api('/agents', { method: 'POST', body: { ...form.value } })
    form.value = { name: '', description: '' }
    await router.push(`/agents/${encodeURIComponent(agent.name)}`)
  } catch (failure) {
    createError.value = failure.message
  } finally {
    creating.value = false
  }
}

function open(name) {
  router.push(`/agents/${encodeURIComponent(name)}`)
}
</script>

<template>
  <h1>Agents</h1>
  <p class="page-intro">
    Every agent that is registered. An agent defined by an <span class="mono">AGENT.md</span>
    directory can be created, edited and archived here; a legacy
    <span class="mono">profiles/*.yaml</span> agent is shown read-only.
  </p>

  <form class="card" style="margin-bottom: 16px" data-test="create-form" @submit.prevent="create">
    <strong>New agent</strong>
    <p class="muted" style="margin: 4px 0 8px">
      Creates a directory from a fixed template. It starts with the offline mock model and no
      tools; nothing is generated by a model.
    </p>
    <div class="row">
      <input
        v-model="form.name"
        placeholder="name (letters, digits, - and _)"
        aria-label="Agent name"
        required
        maxlength="64"
        data-test="create-name"
      />
      <input
        v-model="form.description"
        placeholder="what is it for?"
        aria-label="Agent description"
        required
        maxlength="300"
        style="flex: 1; min-width: 220px"
        data-test="create-description"
      />
      <button class="primary" :disabled="creating" data-test="create-submit">
        {{ creating ? 'Creating…' : 'Create' }}
      </button>
    </div>
    <div v-if="createError" class="notice danger" style="margin: 8px 0 0" data-test="create-error">
      {{ createError }}
    </div>
  </form>

  <AsyncState
    :state="listing.state.value"
    :error="listing.error.value"
    empty-text="No agents are registered yet. Create one above."
    @retry="listing.reload"
  >
    <div
      v-if="Object.keys(listing.data.value.problems).length"
      class="notice danger"
      data-test="problems"
    >
      <strong>Not registered or not applied:</strong>
      <div v-for="(why, dir) in listing.data.value.problems" :key="dir" class="wrap mono">
        {{ dir }}: {{ why }}
      </div>
    </div>
    <div class="grid">
      <div
        v-for="agent in listing.data.value.agents"
        :key="agent.name"
        class="card clickable"
        style="cursor: pointer"
        data-test="agent"
        @click="open(agent.name)"
      >
        <div class="row" style="justify-content: space-between">
          <strong>{{ agent.name }}</strong>
          <StatusBadge :tone="agent.editable ? 'ok' : 'neutral'">
            {{ agent.editable ? 'AGENT.md' : 'legacy, read-only' }}
          </StatusBadge>
        </div>
        <p class="muted">{{ agent.description || 'No description.' }}</p>
        <dl class="facts">
          <dt>Model</dt>
          <dd>{{ agent.provider }} / {{ agent.model }}</dd>
          <dt>Tools</dt>
          <dd>
            <span v-for="tool in agent.tools" :key="tool" class="chip">{{ tool }}</span>
            <span v-if="!agent.tools.length" class="muted">none</span>
          </dd>
          <dt>Schedules</dt>
          <dd>{{ agent.schedules.length }}</dd>
          <dt>Memory</dt>
          <dd>{{ agent.privateMemory ? 'private' : 'shared (global)' }}</dd>
        </dl>
        <div v-if="agent.problem" class="notice danger" style="margin: 8px 0 0">
          {{ agent.problem }}
        </div>
      </div>
    </div>
  </AsyncState>
</template>

